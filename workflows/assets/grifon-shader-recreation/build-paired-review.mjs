// Private inspection only: one decoded timeline prevents two-player presentation drift.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../../..');
const toolRoot=process.env.GRIFON_TOOL_ROOT||'C:/Users/ADMIN/Desktop/grifon-command';
const ffmpeg=path.join(toolRoot,'node_modules/ffmpeg-static/ffmpeg.exe');
const ffprobe=path.join(toolRoot,'.tools/media-runtime/node_modules/ffprobe-static/bin/win32/x64/ffprobe.exe');
const source=path.join(here,'reference/source-x.mp4');
const pilot=path.join(here,'grifon-opening-pilot-silent.mp4');
const sha=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const sourceHash='47c8bbc8e3d06953dd850500e4c7702ce690b3a4bc6708c4fc6a1f3d392df089';
if(sha(source)!==sourceHash)throw new Error('Native reference hash changed');
const inputPilotHash=sha(pilot);
const outDir=path.join(here,'.tmp');fs.mkdirSync(outDir,{recursive:true});
const output=path.join(outDir,'paired-pilot.mp4');
const filter='[0:v]trim=end_frame=222,setpts=PTS-STARTPTS,scale=960:540,setsar=1[a];[1:v]trim=end_frame=222,setpts=PTS-STARTPTS,scale=960:540,setsar=1[b];[a][b]hstack=inputs=2:shortest=1[v]';
const args=['-hide_banner','-loglevel','error','-y','-i',source,'-i',pilot,'-filter_complex',filter,'-map','[v]','-an','-frames:v','222','-c:v','libx264','-preset','fast','-crf','19','-pix_fmt','yuv420p','-movflags','+faststart',output];
const encoded=spawnSync(ffmpeg,args,{encoding:'utf8'});
if(encoded.status!==0)throw new Error(`FFmpeg ${encoded.status}: ${encoded.stderr}`);
const probed=spawnSync(ffprobe,['-v','error','-count_frames','-show_streams','-show_format','-of','json',output],{encoding:'utf8'});
if(probed.status!==0)throw new Error(`FFprobe ${probed.status}: ${probed.stderr}`);
const probe=JSON.parse(probed.stdout),video=probe.streams.find(s=>s.codec_type==='video');
if(video.width!==1920||video.height!==540||Number(video.nb_read_frames)!==222||video.avg_frame_rate!=='30000/1001'||probe.streams.some(s=>s.codec_type==='audio'))throw new Error('Paired review media contract failed');
const decoded=spawnSync(ffmpeg,['-hide_banner','-loglevel','error','-xerror','-i',output,'-f','null','-'],{encoding:'utf8'});
if(decoded.status!==0)throw new Error(`Strict decode ${decoded.status}: ${decoded.stderr}`);
if(sha(pilot)!==inputPilotHash)throw new Error('Pilot changed during pair creation');
const receipt={purpose:'PRIVATE reference-fidelity inspection; not a Grifon export',createdAt:new Date().toISOString(),inputs:{reference:{sha256:sourceHash,bytes:fs.statSync(source).size},pilot:{sha256:inputPilotHash,bytes:fs.statSync(pilot).size}},output:{path:path.relative(root,output).replaceAll('\\','/'),sha256:sha(output),bytes:fs.statSync(output).size,width:1920,height:540,frames:222,fps:'30000/1001',audio:false},layout:{left:'REFERENCE, frames0-221 at960x540',right:'GRIFON, same native frames at960x540'},method:filter,checks:{encode:encoded.status,probe:probed.status,strictDecode:decoded.status,inputHashesStable:true}};
fs.writeFileSync(path.join(here,'qa/paired-review-receipt.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt));
