#!/usr/bin/env node
/**
 * build-gabriel-review.mjs — the Oceanides review sheet (Gabriel plates + the price page on mobile).
 *
 * WHY A BUILD SCRIPT AND NOT A HAND-WRITTEN PAGE
 * The artifact CSP blocks every external request, so the fonts and all seven images
 * have to be inlined as data URIs. Doing that by hand would mean passing ~500 KB of
 * base64 through a chat turn — which is exactly how the first attempt at emailing
 * these plates failed (the string got truncated mid-transfer and Gmail rejected it).
 * Here the bytes never leave the disk.
 *
 * SOURCES ARE COMMITTED ONLY — never `.tmp/` — per the CLAUDE.md artifact rule, so a
 * post-defreezer session can rebuild this from a fresh clone.
 * EXCEPTION, deliberate: the two page screenshots live in `.tmp/shots/`. They are
 * regenerated by driving the dev server, not by reading a committed file, so there is
 * nothing to commit. If they are missing the script says so and skips that section
 * rather than dying — the Gabriel half still builds.
 *
 * DESIGN: clients/oceanides/DESIGN.md, NOT the Grifon NOIR default. This is client
 * work, and CLAUDE.md carves it out explicitly: navy + amber matte print, no glass,
 * no #FFCC00, no charcoal. Getting this backwards cost a full artifact rebuild on
 * 2026-07-28.
 *
 * Run from the repo root:  node tools/artifacts/build-gabriel-review.mjs
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
const TPL = join(HERE, 'gabriel-review.tpl.html');
const OUT = join(ROOT, 'artifacts', 'gabriel-review.html');

const FONT_DIR = join(ROOT, 'funnels', 'oceanides-price-page', 'node_modules', '@fontsource');
const PLATES = join(ROOT, 'clients', 'oceanides', 'kuya-gabriel', 'identity-lock');
const SHOTS = join(ROOT, '.tmp', 'shots');

const kb = (n) => `${Math.round(n / 1024)} KB`;

/** woff2 → data URI. Inlined, never linked: the CSP kills font CDNs silently. */
const font = async (pkg, file) => {
  const buf = await readFile(join(FONT_DIR, pkg, 'files', file));
  return `data:font/woff2;base64,${buf.toString('base64')}`;
};

/** image → webp data URI at a target width. */
const img = async (path, width, quality = 72) => {
  const buf = await sharp(path).resize({ width, withoutEnlargement: true }).webp({ quality }).toBuffer();
  return { uri: `data:image/webp;base64,${buf.toString('base64')}`, bytes: buf.byteLength };
};

const tokens = {};
let total = 0;

// --- fonts -----------------------------------------------------------------
tokens.__FONT_ANTON__ = await font('anton', 'anton-latin-400-normal.woff2');
tokens.__FONT_INTER_400__ = await font('inter', 'inter-latin-400-normal.woff2');
tokens.__FONT_INTER_700__ = await font('inter', 'inter-latin-700-normal.woff2');

// --- Gabriel plates --------------------------------------------------------
// The FINAL set. The rejected iterations (website v1-v3, cover v1-v2) were
// deleted after Gabriel's own eye caught the big head, the pasted look and the
// skin standing out. Their stories live in clients/oceanides/kuya-gabriel/IDENTITY.md.
const plateJobs = [
  ['__PLATE_PROFILE__', 'gabriel-profile-v2.png', 720],
  ['__PLATE_WEBSITE__', 'gabriel-website-v4.png', 620],
  ['__PLATE_COVER__', 'gabriel-cover-v3.png', 900],
  ['__PLATE_POINTING__', 'gabriel-pointing-v1.png', 620],
];
for (const [token, file, width] of plateJobs) {
  const { uri, bytes } = await img(join(PLATES, file), width);
  tokens[token] = uri;
  total += bytes;
  console.log(`  ${file.padEnd(26)} ${kb(bytes)}`);
}

// --- page screenshots (optional) ------------------------------------------
// 390px-wide full-page captures. They stay at their capture width so the phone
// frames in the page render them 1:1 — downscaling a 7,500px-tall screenshot
// turns the body copy to mush, which defeats the point of showing it at all.
const shotJobs = [
  ['__SHOT_LANDING__', 'price-page-390-full.png'],
  ['__SHOT_THANKYOU__', 'thankyou-390-full.png'],
];
let haveShots = true;
for (const [token, file] of shotJobs) {
  const path = join(SHOTS, file);
  if (!existsSync(path)) {
    console.warn(`  ⚠ missing ${file} — re-capture with smoke-tester at 390x844`);
    tokens[token] = '';
    haveShots = false;
    continue;
  }
  const { uri, bytes } = await img(path, 390, 78);
  tokens[token] = uri;
  total += bytes;
  console.log(`  ${file.padEnd(26)} ${kb(bytes)}`);
}
tokens.__SHOTS_DISPLAY__ = haveShots ? 'block' : 'none';

// --- substitute ------------------------------------------------------------
let html = await readFile(TPL, 'utf8');
for (const [token, value] of Object.entries(tokens)) {
  html = html.split(token).join(value);
}

// Hard-fail on any unsubstituted token. A live page with a raw `__PLATE_X__` in it
// is worse than a build error, because it ships looking almost right.
const leftover = html.match(/__[A-Z0-9_]+__/g);
if (leftover) {
  console.error(`\nFAILED — unsubstituted tokens: ${[...new Set(leftover)].join(', ')}`);
  process.exit(1);
}

// clients/oceanides/DESIGN.md + the CLAUDE.md artifact rules, enforced not trusted.
const banned = [
  ['background-clip:text', /background-clip\s*:\s*text/i],
  ['#FFCC00 (Grifon gold)', /#ffcc00/i],
  ['backdrop-filter (walang glass)', /backdrop-filter/i],
];
for (const [label, re] of banned) {
  if (re.test(html)) {
    console.error(`\nFAILED — banned pattern present: ${label}`);
    process.exit(1);
  }
}

// TWO OUTPUTS, and the difference is not cosmetic.
//
// The Artifact tool wraps whatever it publishes in its own
// `<!doctype html><head>…</head><body>` skeleton, so the file it receives must be
// a BODY FRAGMENT with no document tags of its own.
//
// The committed twin is opened DIRECTLY off disk — Neil sends it over Viber or
// email and someone double-clicks it. With no `<meta charset>`, Chromium guesses
// windows-1252 and every `·` in the copy renders as `Â·`. Caught by the mobile
// gate on 2026-07-30, visible on both breakpoints. The hosted page was fine the
// whole time because the wrapper declares the charset; only the twin broke, and
// the twin is the entire reason the file exists.
//
// So: fragment for publishing, full document for sharing.
const FRAGMENT = join(ROOT, '.tmp', 'gabriel-review.fragment.html');
const standalone = `<!doctype html>
<html lang="tl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Kuya Gabriel + ang price page</title>
</head>
<body>
${html}
</body>
</html>
`;

await mkdir(dirname(OUT), { recursive: true });
await mkdir(dirname(FRAGMENT), { recursive: true });
await writeFile(OUT, standalone, 'utf8');
await writeFile(FRAGMENT, html, 'utf8');

console.log(`\n  images ${kb(total)}  ·  page ${kb(Buffer.byteLength(standalone))}`);
console.log(`  → ${OUT}          (standalone twin, i-share ito)`);
console.log(`  → ${FRAGMENT}   (fragment, ito ang ipa-publish)`);
