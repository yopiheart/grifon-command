import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { checkCodexSkills } from './check-codex-skills.mjs';

function fixture(t, body) {
  const root = mkdtempSync(path.join(tmpdir(), 'codex-skills-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const directory = path.join(root, '.agents/skills/example');
  mkdirSync(directory, { recursive: true });
  writeFileSync(path.join(directory, 'SKILL.md'), `---\nname: example\ndescription: Test skill\n---\n${body}`);
  return { root, directory };
}

test('rejects broken migration paths and fictitious platform links', (t) => {
  const { root } = fixture(t, 'node .Codex/skills/example/run.mjs\n[docs](https://code.Codex.com/docs/en/goal)');
  const result = checkCodexSkills(root);
  assert.equal(result.skills, 1);
  assert.ok(result.errors.some((error) => error.includes('invalid .Codex')));
  assert.ok(result.errors.some((error) => error.includes('invented Codex')));
});

test('validates actual local dependencies, not just link syntax', (t) => {
  const { root, directory } = fixture(t, '[rules](rules.md)\nnode .agents/skills/example/run.mjs');
  assert.equal(checkCodexSkills(root).errors.length, 2);
  writeFileSync(path.join(directory, 'rules.md'), 'Rules');
  writeFileSync(path.join(directory, 'run.mjs'), '// Local helper');
  assert.deepEqual(checkCodexSkills(root).errors, []);
});

test('rejects malformed metadata and unguarded legacy evaluation', (t) => {
  const { root, directory } = fixture(t, 'Skill');
  writeFileSync(path.join(directory, 'run_eval.py'), 'cmd = ["claude", "-p"]');
  writeFileSync(path.join(directory, 'SKILL.md'), '---\nname: wrong\n---\nSkill');
  const errors = checkCodexSkills(root).errors;
  assert.ok(errors.some((error) => error.includes('frontmatter')));
  assert.ok(errors.some((error) => error.includes('name differs')));
  assert.ok(errors.some((error) => error.includes('unguarded Claude')));
});

test('rejects literal CR escapes in agent contracts', (t) => {
  const { root } = fixture(t, 'Skill');
  const agents = path.join(root, '.codex/agents');
  mkdirSync(agents, { recursive: true });
  writeFileSync(path.join(agents, 'test.toml'), 'developer_instructions = """hello\\r\nworld"""');
  assert.ok(checkCodexSkills(root).errors.some((error) => error.includes('literal CR')));
});

test('resolves URL-encoded spaces in local Markdown links', (t) => {
  const { root, directory } = fixture(t, '[reference](approved%20image.md)');
  writeFileSync(path.join(directory, 'approved image.md'), 'Approved reference');
  assert.deepEqual(checkCodexSkills(root).errors, []);
});

test('ignores Python bytecode generated by later helper validation', (t) => {
  const { root, directory } = fixture(t, 'Skill');
  const before = checkCodexSkills(root);
  mkdirSync(path.join(directory, '__pycache__'));
  writeFileSync(path.join(directory, '__pycache__/helper.pyc'), 'generated');
  assert.deepEqual(checkCodexSkills(root), before);
});
