 const metrics=await frame.evaluate(()=>{
  const snapshot=window.grifonDebug.snapshot();
  const gl=document.querySelector('canvas').getContext('webgl2'); const ext=gl.getExtension('WEBGL_debug_renderer_info');
  return {renderer:ext?gl.getParameter(ext.UNMASKED_RENDERER_WEBGL):gl.getParameter(gl.RENDERER),frameCount:snapshot.frameCount,frameTimes:snapshot.frameTimes??snapshot.rollingFrameTimes??[],state:snapshot.reaction.state};
 });
 const calls=await page.evaluate(()=>window.companionFixture.snapshot().calls.map(({name,value})=>({name,...(typeof value==='string'||typeof value==='number'?{value}: {})})));
 const sources=['App.tsx','components/CompanionChat/CompanionAvatar.tsx','components/CompanionChat/CompanionChatSurface.tsx','components/CompanionChat/index.tsx','components/OneShotAd/ProducerFlow.tsx','services/companionIntake.ts','public/companion/bridge.js','public/companion/main.js','public/companion/reactions.js','dev/companionChatPreview.tsx','companion-chat-preview.html'];
