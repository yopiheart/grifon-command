import { jsPDF } from 'jspdf';

export const PDF_TOKENS = {
  margin: 14,                     // mm
  goldHex: '#FFCC00',
  inkHex: '#0A0A0A',              // near-black body
  mutedHex: '#6B7280',            // zinc-500-ish
  ruleHex: '#E5E7EB',             // light gray rule
  fineRuleHex: '#F3F4F6',         // hair rule
  pageWidth: 210,                 // A4 portrait
  pageHeight: 297,
  headerHeight: 30,               // reserved at top of every page (logo + gold rule)
  footerReserved: 14,             // reserved at bottom (footer + margin)
  contentTop: 32,                 // first cursorY on a fresh page (after header)
};

export interface PdfDoc {
  doc: jsPDF;
  cursorY: number;
  page: number;
  logoBase64: string | null;
}

// jsPDF default Helvetica is WinAnsi-encoded — peso symbol U+20B1 doesn't render.
// Substitute with "PHP " which reads cleanly and is unambiguous in the Filipino SMB context.
const sanitize = (s: string): string => (s ?? '').replace(/₱/g, 'PHP ');

let logoPromise: Promise<string | null> | null = null;
async function loadLogoBase64(): Promise<string | null> {
  if (!logoPromise) {
    logoPromise = (async () => {
      try {
        const res = await fetch('/logo.png');
        if (!res.ok) return null;
        const blob = await res.blob();
        return await new Promise<string>((resolve, reject) => {
          const reader = new FileReader();
          reader.onloadend = () => resolve(reader.result as string);
          reader.onerror = reject;
          reader.readAsDataURL(blob);
        });
      } catch {
        return null;
      }
    })();
  }
  return logoPromise;
}

export async function createBrandedPdf(opts: { title: string; subtitle?: string }): Promise<PdfDoc> {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  doc.setProperties({
    title: opts.title,
    subject: opts.subtitle || '',
    author: 'Grifon Command',
    creator: 'Grifon Command — grifon.ai',
  });
  const logoBase64 = await loadLogoBase64();
  const ctx: PdfDoc = { doc, cursorY: 0, page: 1, logoBase64 };
  drawHeader(ctx);
  ctx.cursorY = PDF_TOKENS.contentTop;
  return ctx;
}

export function drawHeader(ctx: PdfDoc): void {
  const { doc, logoBase64 } = ctx;
  const m = PDF_TOKENS.margin;

  if (logoBase64) {
    try {
      doc.addImage(logoBase64, 'PNG', m, 8, 14, 14);
    } catch {
      // fall through to text-only header
    }
  }

  const wordmarkX = logoBase64 ? m + 18 : m;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(PDF_TOKENS.inkHex);
  doc.text('GRIFON COMMAND', wordmarkX, 14);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(PDF_TOKENS.mutedHex);
  doc.text('// NEURAL_ENGINE_ACTIVE', wordmarkX, 19);

  // Gold rule
  doc.setDrawColor(PDF_TOKENS.goldHex);
  doc.setLineWidth(0.5);
  doc.line(m, 26, PDF_TOKENS.pageWidth - m, 26);
}

function drawFooter(ctx: PdfDoc, totalPages: number): void {
  const { doc, page } = ctx;
  const m = PDF_TOKENS.margin;
  const y = PDF_TOKENS.pageHeight - 8;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(PDF_TOKENS.mutedHex);
  doc.text('Generated by Grifon Command — grifon.ai', m, y);

  const pageStr = `Page ${page} of ${totalPages}`;
  const pageW = doc.getTextWidth(pageStr);
  doc.text(pageStr, PDF_TOKENS.pageWidth - m - pageW, y);
}

export function ensureSpace(ctx: PdfDoc, neededMm: number): void {
  const limit = PDF_TOKENS.pageHeight - PDF_TOKENS.footerReserved;
  if (ctx.cursorY + neededMm > limit) {
    ctx.doc.addPage();
    ctx.page += 1;
    drawHeader(ctx);
    ctx.cursorY = PDF_TOKENS.contentTop;
  }
}

export function drawCoverTitle(ctx: PdfDoc, title: string, subtitle?: string): void {
  ensureSpace(ctx, 26);
  const { doc } = ctx;
  const m = PDF_TOKENS.margin;
  const maxW = PDF_TOKENS.pageWidth - 2 * m;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(PDF_TOKENS.inkHex);
  const titleLines = doc.splitTextToSize(sanitize(title), maxW);
  doc.text(titleLines, m, ctx.cursorY);
  ctx.cursorY += titleLines.length * 8 + 1;

  if (subtitle) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(11);
    doc.setTextColor(PDF_TOKENS.mutedHex);
    const subLines = doc.splitTextToSize(sanitize(subtitle), maxW);
    doc.text(subLines, m, ctx.cursorY);
    ctx.cursorY += subLines.length * 5 + 3;
  }

  doc.setDrawColor(PDF_TOKENS.goldHex);
  doc.setLineWidth(0.6);
  doc.line(m, ctx.cursorY, m + 40, ctx.cursorY);
  ctx.cursorY += 6;
}

export function drawSectionHeader(ctx: PdfDoc, label: string, title: string): void {
  ensureSpace(ctx, 14);
  const { doc } = ctx;
  const m = PDF_TOKENS.margin;
  const maxW = PDF_TOKENS.pageWidth - 2 * m;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(PDF_TOKENS.goldHex);
  doc.text(sanitize(label).toUpperCase(), m, ctx.cursorY);
  ctx.cursorY += 4;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(PDF_TOKENS.inkHex);
  const titleLines = doc.splitTextToSize(sanitize(title), maxW);
  doc.text(titleLines, m, ctx.cursorY);
  ctx.cursorY += titleLines.length * 6 + 3;
}

export function drawWrappedText(
  ctx: PdfDoc,
  text: string,
  opts?: { italic?: boolean; size?: number; color?: string },
): void {
  if (!text) return;
  const { doc } = ctx;
  const m = PDF_TOKENS.margin;
  const maxW = PDF_TOKENS.pageWidth - 2 * m;

  doc.setFont('helvetica', opts?.italic ? 'italic' : 'normal');
  doc.setFontSize(opts?.size ?? 10);
  doc.setTextColor(opts?.color ?? PDF_TOKENS.inkHex);
  const lines = doc.splitTextToSize(sanitize(text), maxW);
  ensureSpace(ctx, lines.length * 5 + 2);
  doc.text(lines, m, ctx.cursorY);
  ctx.cursorY += lines.length * 5 + 2;
}

export function drawKeyValueRow(ctx: PdfDoc, key: string, value: string): void {
  if (!value) return;
  const { doc } = ctx;
  const m = PDF_TOKENS.margin;
  const valueX = m + 32;
  const valueW = PDF_TOKENS.pageWidth - 2 * m - 32;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(PDF_TOKENS.mutedHex);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(PDF_TOKENS.inkHex);
  const valueLines = doc.splitTextToSize(sanitize(value), valueW);
  const blockH = Math.max(5, valueLines.length * 5);
  ensureSpace(ctx, blockH + 1);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(PDF_TOKENS.mutedHex);
  doc.text(sanitize(key).toUpperCase(), m, ctx.cursorY);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(PDF_TOKENS.inkHex);
  doc.text(valueLines, valueX, ctx.cursorY);

  ctx.cursorY += blockH + 1;
}

export function drawAnchorPrice(ctx: PdfDoc, totalValue: string, actualPrice: string): void {
  ensureSpace(ctx, 18);
  const { doc } = ctx;
  const m = PDF_TOKENS.margin;
  const startY = ctx.cursorY;

  // Total value (small, muted, strikethrough)
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(PDF_TOKENS.mutedHex);
  doc.text('TOTAL VALUE', m, startY);

  doc.setFontSize(11);
  const totalText = sanitize(totalValue);
  doc.text(totalText, m, startY + 6);
  const totalW = doc.getTextWidth(totalText);
  doc.setDrawColor(PDF_TOKENS.mutedHex);
  doc.setLineWidth(0.3);
  doc.line(m, startY + 5, m + totalW, startY + 5);

  // Actual price (large, gold, bold) on the right
  const priceX = PDF_TOKENS.pageWidth - m - 60;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(PDF_TOKENS.mutedHex);
  doc.text('YOUR PRICE', priceX, startY);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(PDF_TOKENS.goldHex);
  doc.text(sanitize(actualPrice), priceX, startY + 8);

  ctx.cursorY = startY + 14;
}

export function drawTwoColumnTable(
  ctx: PdfDoc,
  header: string,
  rows: { left: string; right: string }[],
): void {
  if (!rows?.length) return;
  const { doc } = ctx;
  const m = PDF_TOKENS.margin;
  const maxW = PDF_TOKENS.pageWidth - 2 * m;
  const rightColW = 36;
  const leftColW = maxW - rightColW - 4;

  ensureSpace(ctx, 12);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(PDF_TOKENS.mutedHex);
  doc.text(sanitize(header).toUpperCase(), m, ctx.cursorY);
  ctx.cursorY += 3;

  doc.setDrawColor(PDF_TOKENS.ruleHex);
  doc.setLineWidth(0.2);
  doc.line(m, ctx.cursorY, PDF_TOKENS.pageWidth - m, ctx.cursorY);
  ctx.cursorY += 3;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  for (const row of rows) {
    const leftLines = doc.splitTextToSize(sanitize(row.left), leftColW);
    const rowH = Math.max(5, leftLines.length * 5);
    ensureSpace(ctx, rowH + 2);

    doc.setTextColor(PDF_TOKENS.inkHex);
    doc.text(leftLines, m, ctx.cursorY);

    doc.setTextColor(PDF_TOKENS.mutedHex);
    const rightText = sanitize(row.right);
    const rightW = doc.getTextWidth(rightText);
    doc.text(rightText, PDF_TOKENS.pageWidth - m - rightW, ctx.cursorY);

    ctx.cursorY += rowH;

    doc.setDrawColor(PDF_TOKENS.fineRuleHex);
    doc.setLineWidth(0.15);
    doc.line(m, ctx.cursorY + 0.5, PDF_TOKENS.pageWidth - m, ctx.cursorY + 0.5);
    ctx.cursorY += 2;
  }
  ctx.cursorY += 1;
}

export function drawColorSwatches(ctx: PdfDoc, label: string, hexCodes: string[]): void {
  if (!hexCodes?.length) return;
  const { doc } = ctx;
  const m = PDF_TOKENS.margin;

  ensureSpace(ctx, 12);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(PDF_TOKENS.mutedHex);
  doc.text(sanitize(label).toUpperCase(), m, ctx.cursorY);
  ctx.cursorY += 4;

  let x = m;
  const swatchSize = 5;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  for (const hex of hexCodes) {
    const safeHex = /^#?[0-9A-Fa-f]{6}$/.test(hex.trim()) ? (hex.trim().startsWith('#') ? hex.trim() : `#${hex.trim()}`) : '#CCCCCC';
    doc.setFillColor(safeHex);
    doc.setDrawColor(PDF_TOKENS.ruleHex);
    doc.setLineWidth(0.15);
    doc.rect(x, ctx.cursorY - swatchSize + 1, swatchSize, swatchSize, 'FD');
    doc.setTextColor(PDF_TOKENS.inkHex);
    const labelText = safeHex.toUpperCase();
    doc.text(labelText, x + swatchSize + 1.5, ctx.cursorY);
    x += swatchSize + 1.5 + doc.getTextWidth(labelText) + 5;
    if (x > PDF_TOKENS.pageWidth - m - 30) {
      ctx.cursorY += 6;
      x = m;
      ensureSpace(ctx, 6);
    }
  }
  ctx.cursorY += 6;
}

export function finalizePdf(ctx: PdfDoc): Blob {
  const totalPages = ctx.doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    ctx.doc.setPage(i);
    ctx.page = i;
    drawFooter(ctx, totalPages);
  }
  return ctx.doc.output('blob');
}
